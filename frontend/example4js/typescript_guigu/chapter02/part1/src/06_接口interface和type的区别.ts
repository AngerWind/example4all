(function () {

    /**
     * interface 和 type 都能定义对象类型, 大部分场景都可以互换
     */
        // interface
    interface User {
        name: string;
        age: number;
    }
    const user: User = {
        name: 'sss',
        age: 11,
    }

    // type
    type User1 = {
        name: string;
        age: number;
    }
    const user2: User1 = {
        name: 'sss',
        age: 11,
    }

    /**
     *  不同点
     *
     *   ┌──────────────────────┬───────────────────────┬─────────────────┐
     *   │         特性          │       interface       │      type       │
     *   ├──────────────────────┼───────────────────────┼─────────────────┤
     *   │ 定义对象类型            │ ✅                    │ ✅              │
     *   ├──────────────────────┼───────────────────────┼─────────────────┤
     *   │ 定义基本类型别名        │ ❌                    │ ✅              │
     *   ├──────────────────────┼───────────────────────┼─────────────────┤
     *   │ 定义联合类型            │ ❌                    │ ✅              │
     *   ├──────────────────────┼───────────────────────┼─────────────────┤
     *   │ 定义元组               │ ❌                    │ ✅              │
     *   ├──────────────────────┼───────────────────────┼─────────────────┤
     *   │ 声明合并（自动合并）     │ ✅                    │ ❌              │
     *   ├──────────────────────┼───────────────────────┼─────────────────┤
     *   │ extends 继承          │ ✅                    │ ❌（用 & 代替） │
     *   ├──────────────────────┼───────────────────────┼─────────────────┤
     *   │ & 交叉                │ ❌（用 extends 代替） │ ✅              │
     *   └──────────────────────┴───────────────────────┴─────────────────┘
     */

    // 1. type 能做的，interface 做不了

    // 基本类型别名
    type Name = string;

    // 联合类型
    type Status = 'active' | 'inactive';

    // 元组
    type Pair = [string, number];

    // 复杂类型运算
    type Nullable<T> = T | null;

    // 2. interface 能做的，type 做不了

    // 声明合并：同名 interface 自动合并
    interface User3 {
        name: string;
    }
    interface User3 {
        age: number;
    }

    // 自动合并为 { name: string; age: number }
    const user3: User3 = { name: '张三', age: 25 };  // ✅

    // 同名 type 会报错：
    // type User = { name: string };
    // type User = { age: number };  // ❌ 重复定义报错

    // 3. 继承方式不同
    // interface 用 extends
    interface Animal1 {
        name: string;
    }
    interface Dog1 extends Animal1 {
        breed: string;
    }

    // type 用 &
    type Animal2 = {
        name: string;
    }
    type Dog2 = Animal2 & {
        breed: string;
    }

    /**
     *  怎么选
     *
     *   ┌────────────────────────────────┬────────────────────┐
     *   │              场景               │        推荐        │
     *   ├────────────────────────────────┼────────────────────┤
     *   │ 定义对象结构                     │ interface          │
     *   ├────────────────────────────────┼────────────────────┤
     *   │ 需要声明合并（扩展第三方类型）       │ interface          │
     *   ├────────────────────────────────┼────────────────────┤
     *   │ 联合类型、基本类型别名             │ type               │
     *   ├────────────────────────────────┼────────────────────┤
     *   │ 元组、复杂类型运算                │ type               │
     *   ├────────────────────────────────┼────────────────────┤
     *   │ 其他情况                         │ 都行，团队统一即可    │
     *   └────────────────────────────────┴────────────────────┘
     *
     *   简单原则：定义对象用 interface，其他用 type。
     */


})();